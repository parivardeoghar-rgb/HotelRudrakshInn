export function sanitizeId(raw: string): string {
  const cleaned = raw.replace(/[^a-zA-Z0-9_-]/g, '_').slice(0, 120);
  return cleaned || `id_${Date.now()}`;
}

export function emailToInviteId(email: string): string {
  return `inv_${email.trim().toLowerCase().replace(/[^a-z0-9]/g, '_').slice(0, 110)}`;
}

export function createDocId(prefix: string): string {
  const rand = Math.random().toString(36).slice(2, 8);
  return sanitizeId(`${prefix}_${Date.now()}_${rand}`);
}
